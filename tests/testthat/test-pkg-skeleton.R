# =============================================================================
# test-pkg-skeleton.R — garde du jalon M3 (D2) : squelette package quasi vide
# =============================================================================
# Plan D2, M3 : « Créer le squelette DESCRIPTION/NAMESPACE (roxygen) vide,
# avec R CMD check qui passe sur un package quasi vide — le vrai premier
# contact D2 avec R CMD check, sans déplacer une ligne de code applicative. »
#
# Placement mesuré : tools/pkg_skeleton/ (PAS à la racine — une DESCRIPTION à
# la racine ferait traiter les 78 fichiers de R/ comme du code de package par
# R CMD check, ce qui n'est pas « quasi vide » ; de plus elle changerait la
# détection de type de projet partout : renv, testthat, shinytest2). M4+
# (extraction du premier domaine) déplacera ce squelette à la racine — c'est
# LUI qui devra re-basereler ce garde, délibérément.
#
# ⚠ artefact d'environnement mesuré : Git Bash exporte LC_CTYPE=C.UTF-8
# (inconnu de R sous Windows) ; les processus ENFANTS de R CMD check émettent
# alors un warning de démarrage sur stderr et le check le compte comme ERROR.
# Correctif : Sys.setenv(LC_CTYPE="C", LANG="C") dans le processus père avant
# system2 (l'argument env= de system2 est IGNORÉ sous Windows — mesuré), avec
# restauration via on.exit. Vérifié exit 0 / aucune ERROR le 2026-10-24.
# =============================================================================
.pks_root <- ts_project_root()
.pks_skel <- file.path(.pks_root, "tools", "pkg_skeleton")

test_that("M3 : le squelette existe et DESCRIPTION a ses champs obligatoires", {
  d <- file.path(.pks_skel, "DESCRIPTION")
  expect_true(file.exists(d), info = "tools/pkg_skeleton/DESCRIPTION absent (M3 non livré)")  # RED avant M3
  fields <- read.dcf(d)[1L, ]
  for (f in c("Package", "Version", "Title", "Description",
              "Author", "Maintainer", "License", "Encoding")) {
    expect_true(!is.na(fields[[f]]) && nzchar(fields[[f]]),
                info = sprintf("champ DESCRIPTION absent/vide : %s", f))
  }
  expect_identical(fields[["Package"]], "TranscriptoShiny")
})

test_that("M3 : NAMESPACE est un squelette roxygen2", {
  n <- file.path(.pks_skel, "NAMESPACE")
  expect_true(file.exists(n), info = "tools/pkg_skeleton/NAMESPACE absent (M3 non livré)")  # RED avant M3
  lines <- readLines(n, warn = FALSE)
  expect_true(any(grepl("Generated by roxygen2", lines, fixed = TRUE)),
              info = "en-tête roxygen2 manquant dans NAMESPACE")
})

test_that("M3 : R CMD check passe sur le squelette quasi vide (exit 0, zéro ERROR)", {
  skip_if(!file.exists(file.path(.pks_skel, "DESCRIPTION")),
          "squelette absent — couvert par le bloc précédent")
  rex <- file.path(R.home("bin"), if (.Platform$OS.type == "windows") "R.exe" else "R")
  skip_if(!file.exists(rex), "binaire R introuvable")
  # Copie sous tempdir() : le check écrit <pkg>.Rcheck dans le répertoire de
  # travail — il ne doit JAMAIS atterrir dans l'arbre du dépôt.
  work <- file.path(tempdir(), "m3_pkg_check")
  unlink(work, recursive = TRUE)
  pkg <- file.path(work, "TranscriptoShiny")
  dir.create(pkg, recursive = TRUE)
  file.copy(file.path(.pks_skel, c("DESCRIPTION", "NAMESPACE")), pkg,
            overwrite = TRUE)
  out <- tempfile("m3-rcmdcheck-")
  old_lc <- Sys.getenv(c("LC_CTYPE", "LANG"))
  old_wd <- getwd()
  Sys.setenv(LC_CTYPE = "C", LANG = "C")
  setwd(work)
  on.exit({
    setwd(old_wd)
    do.call(Sys.setenv, as.list(old_lc))
    unlink(work, recursive = TRUE)
  }, add = TRUE)
  st <- suppressWarnings(system2(rex, c("CMD", "check", "--no-manual", shQuote(pkg)),
                                 stdout = out, stderr = out, timeout = 300))
  got <- if (file.exists(out)) readLines(out, warn = FALSE) else character()
  expect_identical(as.integer(st), 0L,
                   info = paste(utils::head(got, 20L), collapse = " | "))
  expect_false(any(grepl("ERROR", got)),
               info = paste(grep("ERROR", got, value = TRUE), collapse = " | "))
})
